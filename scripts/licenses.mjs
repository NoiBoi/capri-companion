// Generates THIRD_PARTY_LICENSES.md from installed package metadata.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const read = (name) => {
  const dir = path.join(root, 'node_modules', name);
  const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const lic = fs.readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  return { name, version: meta.version, license: meta.license ?? 'see file', homepage: meta.homepage ?? meta.repository?.url ?? '', text: lic ? fs.readFileSync(path.join(dir, lic), 'utf8').trim() : '' };
};
const shipped = [
  { ...read('electron'), why: 'Application runtime (includes Chromium and Node.js; their notices ship as LICENSES.chromium.html next to Capri.exe)' },
  { ...read('koffi'), why: 'Win32 FFI for fullscreen detection and drag release (runtime dependency)' },
  { ...read('@koromix/koffi-win32-x64'), why: 'koffi native binary for Windows x64' },
  { ...read('zod'), why: 'Settings and IPC validation (bundled into the app code)' },
  { ...read('@google/genai'), why: 'Official Google Gemini SDK (bundled into the main process)' },
];
const dev = Object.keys(pkg.devDependencies).filter((n) => !shipped.some((s) => s.name === n)).map(read);
let md = `# Third-party software\n\nGenerated by \`node scripts/licenses.mjs\`. Capri itself is MIT-licensed (see LICENSE).\n\n## Shipped in the installer\n\n| Package | Version | License | Purpose |\n|---|---|---|---|\n`;
for (const s of shipped) md += `| ${s.name} | ${s.version} | ${s.license} | ${s.why} |\n`;
md += `\n## Build and test tools (not shipped)\n\n| Package | Version | License |\n|---|---|---|\n`;
for (const d of dev) md += `| ${d.name} | ${d.version} | ${d.license} |\n`;
md += `\n## Platform components used at runtime (not redistributed)\n\n- Windows System.Speech (speech recognition and Windows voices), part of Windows.\n- Windows DPAPI via Electron safeStorage (credential encryption), part of Windows.\n\n## Character and trademark notice\n\nCapri, Cyberpunk and Cyberpunk: Edgerunners are trademarks/copyrights of CD PROJEKT S.A., Studio Trigger and Netflix. This is an unofficial, non-commercial fan project. The character artwork is an original vector reconstruction drawn in code; no studio assets, frames, audio or voice data are included.\n\n## License texts\n`;
for (const s of shipped) if (s.text) md += `\n### ${s.name} ${s.version}\n\n\`\`\`\n${s.text}\n\`\`\`\n`;
fs.writeFileSync(path.join(root, 'THIRD_PARTY_LICENSES.md'), md);
console.log(`wrote THIRD_PARTY_LICENSES.md (${shipped.length} shipped, ${dev.length} dev)`);
